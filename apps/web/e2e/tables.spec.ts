/** Evidência D6/D7 aguarda somente a entrada finita do diálogo, sem congelar a Faísca ou usar sleeps arbitrários. */
async function captureManagement(page: Page, info: TestInfo, name: string) {
  for (const dialog of await page.getByRole('dialog').all()) await dialog.evaluate(async (node) => { await Promise.all(node.getAnimations().map((animation) => animation.finished)); });
  await attachShot(page, info, name);
}

