/** Lote de registros tipados; os IDs devolvidos são a evidência de persistência verificada após a UI. */
async function seed(page: Page, table: DataTable, headers: Record<string, string>, creates: { values: Record<string, string | boolean | string[] | null> }[]): Promise<TableRecord[]> {
  // A API grava até 100 registros por lote; a grade pagina de 100 em 100, então cenários de paginação semeiam mais que isso.
  const records: TableRecord[] = [];
  for (let start = 0; start < creates.length; start += 100) {
    const response = await page.request.post(`${ORIGIN}/api/tables/${table.id}/records`, { headers, data: { operationId: randomUUID(), expectedSchemaVersion: table.schemaVersion, creates: creates.slice(start, start + 100) } });
    expect(response.status()).toBe(200);
    records.push(...(await response.json() as { records: TableRecord[] }).records);
  }
  return records;
}
/** Todos os registros pela API, seguindo o cursor (a listagem devolve no máximo 100 por página). */
async function allRecords(page: Page, tableId: string, headers: Record<string, string>): Promise<TableRecord[]> {
  const records: TableRecord[] = []; let cursor: string | null = null;
  do { const body = await (await page.request.get(`${ORIGIN}/api/tables/${tableId}/records?limit=100${cursor ? `&cursor=${cursor}` : ''}`, { headers })).json() as { records: TableRecord[]; nextCursor: string | null }; records.push(...body.records); cursor = body.nextCursor; } while (cursor);
  return records;
}
