  expect(rows.records.map((row) => row.values[relation!.id]).sort()).toEqual([seeded[0]!.id, seeded[1]!.id].sort());
  expect((await page.request.post(`${ORIGIN}/api/tables/${target.id}/records`, { headers, data: { operationId: randomUUID(), expectedSchemaVersion: 1, updates: [{ id: rows.records[0]!.id, expectedVersion: 1, values: { [done!.id]: true } }] } })).status()).toBe(200);
  await run();
  const repeated = await (await page.request.post(`${ORIGIN}/api/tables/${target.id}/query`, { headers, data: {} })).json() as { records: TableRecord[]; totalCount: number };
  expect(repeated.totalCount).toBe(2); expect(repeated.records.find((row) => row.id === rows.records[0]!.id)?.values[done!.id]).toBe(true);
  await page.setViewportSize({ width: 375, height: 812 }); await page.goto(`/bots/${bot.id}/tabelas/${target.id}`);
